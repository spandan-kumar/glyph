// Original bitmap fonts drawn for Glyph. Each glyph is written as rows
// separated by spaces: '#' is lit, '.' is dark. Rows may be omitted at the
// bottom; widths come from the longest row, so fonts are variable-width.

class Glyph {
  Glyph(this.width, this.rows);

  final int width;

  /// One bitmask per font row; bit x is column x.
  final List<int> rows;

  bool on(int x, int y) => (rows[y] >> x) & 1 == 1;
}

class BitmapFont {
  BitmapFont._(this.id, this.name, this.height, this.capHeight, this._glyphs);

  final String id;
  final String name;

  /// Full cell height including the descender row(s).
  final int height;

  /// Rows used by capitals and digits, from the top of the cell.
  final int capHeight;
  final int spacing = 1;
  final Map<int, Glyph> _glyphs;

  Iterable<int> get runes => _glyphs.keys;

  bool has(int rune) => _glyphs.containsKey(rune);

  /// Glyph for [rune]; lowercase falls back to capitals and anything else
  /// unknown to '?'.
  Glyph glyph(int rune) =>
      _glyphs[rune] ??
      (rune >= 0x61 && rune <= 0x7A ? _glyphs[rune - 32] : null) ??
      _glyphs[0x3F]!;

  /// Width in pixels of [text] drawn on one line.
  int measure(String text) {
    var w = 0, n = 0;
    for (final r in text.runes) {
      w += glyph(r).width;
      n++;
    }
    return n == 0 ? 0 : w + (n - 1) * spacing;
  }
}

Map<int, Glyph> _parse(Map<String, String> spec, int height) => {
      for (final MapEntry(:key, :value) in spec.entries)
        key.runes.single: _glyph(value, height),
    };

Glyph _glyph(String spec, int height) {
  final rows = spec.split(' ');
  if (rows.length > height) throw StateError('Glyph taller than $height: $spec');
  final w = rows.fold(0, (m, r) => r.length > m ? r.length : m);
  return Glyph(w, [
    for (var y = 0; y < height; y++)
      y < rows.length ? _bits(rows[y]) : 0,
  ]);
}

int _bits(String row) {
  var m = 0;
  for (var x = 0; x < row.length; x++) {
    if (row[x] == '#') m |= 1 << x;
  }
  return m;
}

/// Widens every stroke by one pixel to the right, except where that would
/// close a one-pixel gap.
Glyph _embolden(Glyph g) {
  final rows = <int>[];
  for (final r in g.rows) {
    var out = r;
    for (var x = 1; x <= g.width; x++) {
      final left = (r >> (x - 1)) & 1, here = (r >> x) & 1, right = (r >> (x + 1)) & 1;
      if (left == 1 && here == 0 && right == 0) out |= 1 << x;
    }
    rows.add(out);
  }
  return Glyph(g.width + 1, rows);
}

