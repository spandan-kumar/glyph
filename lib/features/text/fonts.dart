final tinyFont = BitmapFont._('tiny', 'Tiny', 5, 5, _parse(_tiny, 5));

final classicFont = BitmapFont._('classic', 'Classic', 8, 7, _parse(_classic, 8));

final boldFont = BitmapFont._('bold', 'Bold', 8, 7, {
  for (final MapEntry(:key, :value) in classicFont._glyphs.entries)
    key: _embolden(value),
  ..._parse(_boldOverrides, 8),
});

/// Largest first.
final textFonts = <BitmapFont>[boldFont, classicFont, tinyFont];

BitmapFont fontById(String id) =>
    textFonts.firstWhere((f) => f.id == id, orElse: () => classicFont);

/// [preferred] followed by the smaller fonts, for fitting text into a matrix.
List<BitmapFont> fontFallbacks(String preferred) {
  final f = fontById(preferred);
  return [f, ...textFonts.skip(textFonts.indexOf(f) + 1)];
}
