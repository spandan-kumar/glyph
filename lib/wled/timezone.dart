final Map<String, int> _index = {
  for (final e in _zones.entries)
    for (final z in e.value) z: e.key,
};

/// The WLED entry for an IANA zone id, or null when none matches exactly.
int? wledTimezoneIndex(String? iana) => iana == null ? null : _index[iana];

/// `tz` and extra `offsetSeconds` to write to WLED for this phone. A matched
/// zone needs no extra offset; otherwise UTC plus the phone's current offset.
({int tz, int offsetSeconds}) wledTimezoneFor(
  String? iana,
  Duration utcOffset,
) {
  final i = wledTimezoneIndex(iana);
  if (i != null) return (tz: i, offsetSeconds: 0);
  return (tz: 0, offsetSeconds: utcOffset.inSeconds);
}
